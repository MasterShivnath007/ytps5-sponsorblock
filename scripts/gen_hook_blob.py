#!/usr/bin/env python3
"""Generate a C header containing a raw .text blob.

Usage: gen_hook_blob.py [src.bin] [dst.h] [array_name] [length_name]

With no arguments this preserves the original hook blob output.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent

src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "build" / "hook.bin"
dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "injector" / "hook_blob.h"
array_name = sys.argv[3] if len(sys.argv) > 3 else "ytps5_hook_blob"
length_name = sys.argv[4] if len(sys.argv) > 4 else "ytps5_hook_blob_len"

if not src.is_absolute():
    src = root / src
if not dst.is_absolute():
    dst = root / dst

if not src.exists():
    sys.exit(f"missing {src}; build it first")

data = src.read_bytes()
lines = [
    "/* Generated by scripts/gen_hook_blob.py. Do not edit. */",
    "#pragma once",
    f"static const unsigned char {array_name}[] = {{",
]
for i in range(0, len(data), 16):
    chunk = data[i:i + 16]
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
lines.append("};")
lines.append(f"static const unsigned int {length_name} = {len(data)};")
lines.append("")
dst.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {dst} ({len(data)} bytes)")
